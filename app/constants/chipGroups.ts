// 새 지명도 같은 군으로 자동 분류되게 한다. 매칭 안 되면 '기타'로 안전 폴백.
// 안국(종로)·신당(중구)·중랑(회기 옆)·선정릉(강남)·이수(동작) — 실제 이벤트에 꽤 있는데
// 기존 키워드에 안 걸려 '기타'로 몰렸다(2026-08-24 오너 지적: "기타가 왜 이리 많지").
// 군자(광진구 인근) 추가 — 2026-08-24 오너 지적("충청·호남 갈 것들이 기타에 많다")으로
// 전수 재검토, 경기(가평·포천)·충청(보령·괴산)·호남(완도)·경북(울릉)에도 누락 키워드 보충.
const _GANGNAM = /강남|삼성|역삼|선릉|선정릉|서초|양재|사당|송파|잠실|문정|가락|석촌|방이|강동|천호|압구정|신사|논현|청담|교대|방배|반포|대치|도곡|수서|개포|일원/
const _GANGBUK = /종로|안국|을지로|광화문|시청|중구|신당|충정로|성수|성동|동대문|성북|왕십리|건대|군자|한남|용산|명동|충무로|혜화|대학로|광진|노원|도봉|강북|중랑|미아|수유|창동|상계|회기|이태원|약수|금호|보문/
const _GANGSEO = /홍대|신촌|합정|상수|마포|여의도|영등포|구로|가산|강서|마곡|목동|양천|금천|동작|이수|관악|신림|봉천|당산|문래|대림|화곡|발산|노량진|상도|서대문|은평|연신내|불광|디지털단지/
const _INCHEON = /인천|남동구|주안|송도|부평|계양|연수|미추홀|청라|검단|서구.?인천/
const _GYEONGGI = /수원|광교|분당|판교|일산|고양|부천|안양|평촌|산본|범계|성남|화성|동탄|오산|평택|하남|미사|용인|기흥|수지|죽전|의정부|남양주|김포|파주|광명|시흥|군포|의왕|이천|여주|양평|안산|구리|과천|가평|포천|경기/
// 강원 — 고성은 강원·경남 양쪽에 실존해 문자열만으론 못 가른다(크롤 데이터가 도 단위
// 표기가 없음). 소셜링·소개팅 둘 다 캠핑·여행류에서 나오는 맥락상 강원으로 본다.
const _GANGWON = /강원|원주|춘천|양양|고성|삼척|양구|태백|속초|강릉|동해|철원|화천|인제|홍천|횡성|영월|평창|정선/
const _CHUNGCHEONG = /대전|세종|천안|청주|아산|충주|제천|당진|서산|논산|공주|보령|괴산|둔산|유성|쌍용|불당|두정|충청|충남|충북/
// 경기 '광주시'는 위 _GYEONGGI(경기 literal 포함)가 먼저 잡으므로, 여기 '광주'는 광주광역시로 처리
const _HONAM = /광주|전주|익산|군산|목포|여수|순천|나주|완도|상무|첨단|봉선|전남|전북|호남/
const _GYEONGBUK = /대구|포항|경주|구미|안동|경산|김천|울릉|동성로|수성|범어|상인|경북/
const _GYEONGNAM = /부산|창원|마산|진해|울산|김해|양산|전포|진주|서면|해운대|센텀|남포|광안|사상|동래|삼산|경남/
const _JEJU = /제주|서귀포/

export function regionGroupKey(region: string): string {
  const s = region || ''
  if (_GANGNAM.test(s)) return '강남권'
  if (_GANGBUK.test(s)) return '강북권'
  if (_GANGSEO.test(s)) return '강서권'
  if (_INCHEON.test(s)) return '인천'
  if (_GYEONGGI.test(s)) return '경기'
  if (_GANGWON.test(s)) return '강원'
  if (_CHUNGCHEONG.test(s)) return '충청'
  if (_HONAM.test(s)) return '호남'
  if (_GYEONGBUK.test(s)) return '경북'
  if (_GYEONGNAM.test(s)) return '경남'
  if (_JEJU.test(s)) return '제주'
  if (/서울/.test(s)) return '강북권' // 권 미분류 서울(서울/경기 등)
  return '기타'
}

