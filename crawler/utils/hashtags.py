def derive_socialing_hashtags(
    title: Optional[str],
    category: Optional[str] = None,
) -> list[str]:
    """소셜링 모임 제목 + 원본 카테고리에서 해시태그를 생성한다.
    카테고리 기본 태그(있으면)를 맨 앞에, 그 뒤에 제목에서 뽑은 소재 태그를 붙인다.
    매칭이 하나도 없으면 빈 리스트(호출부에서 빈 배열로 덮지 않도록 처리)."""
    text = (title or '').lower().replace(' ', '')
    result: list[str] = []
    for tag, keywords in SOCIALING_KEYWORDS:
        if tag in result:
            continue
        for kw in keywords:
            if kw.lower().replace(' ', '') in text:
                result.append(tag)
                break
    base = SOCIALING_CATEGORY_BASE.get(category or '')
    if base and base not in result:
        result.insert(0, base)
    return result
